import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { expect } from "playwright/test";

export async function checkThreeInspection({ context, origin, docId, dataDirectory, output, getModelCalls }) {
  const setup = `scene.add(new THREE.AmbientLight(0xffffff,2));
    const part=new THREE.Group();part.userData.study={label:'Core block',description:'A supplied explanation of the illustrative core.',properties:{owner:'Request A',slots:4,shared:false,identifier:'LongIdentifier'.repeat(16)},illustrative:true};group.add(part);
    const core=new THREE.Mesh(new THREE.BoxGeometry(1,1,1),new THREE.MeshStandardMaterial({color:0x0284c7}));part.add(core);
    const anonymous=new THREE.Mesh(new THREE.SphereGeometry(0.3,16,12),new THREE.MeshStandardMaterial({color:0xe87518}));anonymous.position.x=1.3;group.add(anonymous);
    const decoration=new THREE.Mesh(new THREE.BoxGeometry(0.2,0.2,0.2),new THREE.MeshBasicMaterial({color:0x10a050}));decoration.position.x=-1.3;decoration.userData.inspectable=false;group.add(decoration);`;
  const animated = { type: "3d", title: "Inspectable blocks", caption: "Illustrative blocks, not measured geometry.", setup_code: setup + "return {update:function(t){core.rotation.z=t*0.7;}};" };
  const staticSpec = { ...animated, title: "Static blocks", setup_code: setup };
  const tag = { id: "three-test", page: 0, endX: 120, endY: 130, fontHeight: 12, type: "3d", label: animated.title, ready: true, generating: false, spec: animated, revision: 0, versionId: "animated", versions: [{ id: "static", at: 1, spec: staticSpec }], concept: { type: "3d", label: animated.title, context: "Inspect the supplied blocks.", anchor: "Momentum" } };
  await writeFile(path.join(dataDirectory, "docs", docId, "tags.json"), JSON.stringify({ v: 1, docId, savedAt: Date.now(), activeTagId: tag.id, pagesAnalyzed: [0], tags: [tag] }));
  const viewer = await context.newPage();
  await viewer.setViewportSize({ width: 1440, height: 1000 });
  await viewer.goto(`${origin}/viewer/${docId}`);
  const scene = viewer.getByRole("img", { name: "3D visualization", exact: true });
  const controls = viewer.getByRole("group", { name: "3D controls", exact: true });
  const details = viewer.getByRole("dialog", { name: "3D part details", exact: true });
  const frames = () => viewer.evaluate(() => new Promise(resolve => { let remaining = 15; const next = () => --remaining ? requestAnimationFrame(next) : resolve(); requestAnimationFrame(next); }));
  const hash = async () => createHash("sha256").update(await scene.screenshot()).digest("hex");
  const center = async () => { const bounds = await scene.boundingBox(); return { x: bounds.x + bounds.width / 2, y: bounds.y + bounds.height / 2 }; };
  await expect(scene).toBeVisible();
  await expect(controls.getByRole("button", { name: "Pause model animation", exact: true })).toBeEnabled();
  await expect(controls.getByLabel("3D part").locator("option")).toHaveCount(3);
  const calls = getModelCalls();
  await controls.getByRole("button", { name: "Pause rotation", exact: true }).click();
  const animationStart = await hash();
  await expect.poll(hash).not.toBe(animationStart);
  await controls.getByRole("button", { name: "Pause model animation", exact: true }).click();
  await viewer.mouse.move(0, 0);
  await frames();
  const frozen = await hash();
  await frames();
  assert.equal(await hash(), frozen, "Both controls paused produce stable pixels");
  await controls.getByRole("button", { name: "Resume rotation", exact: true }).click();
  await expect.poll(hash).not.toBe(frozen);
  await expect(controls.getByRole("button", { name: "Resume model animation", exact: true })).toBeEnabled();
  await controls.getByRole("button", { name: "Pause rotation", exact: true }).click();
  await controls.getByRole("button", { name: "Reset 3D view", exact: true }).click();
  await frames();
  const reset = await hash();
  const point = await center();
  await viewer.mouse.move(point.x, point.y);
  await expect(viewer.getByRole("tooltip").filter({ hasText: "Core block" })).toContainText("A supplied explanation");
  const highlighted = await hash();
  assert.notEqual(highlighted, reset, "Part picking renders a visible selection outline");
  await viewer.mouse.click(point.x, point.y);
  await viewer.mouse.move(0, 0);
  await expect(details).toContainText("Core block");
  await expect(details).toContainText("Request A");
  await expect(details).toContainText("Illustrative model");
  await expect(details).toContainText("not independently verified");
  await expect(details).toContainText("slots");
  await viewer.screenshot({ path: path.join(output, "three-inspection-desktop.png") });
  await details.getByRole("button", { name: "Close 3D part details", exact: true }).click();
  await frames();
  assert.equal(await hash(), reset, "Clearing selection restores the unchanged original materials");
  await viewer.mouse.move(point.x, point.y);
  await viewer.mouse.down();
  await viewer.mouse.move(point.x + 90, point.y + 30, { steps: 8 });
  await viewer.mouse.up();
  await viewer.mouse.move(0, 0);
  await expect(details).toHaveCount(0);
  await frames();
  assert.notEqual(await hash(), reset, "Dragging orbits instead of selecting a part");
  await controls.getByRole("button", { name: "Reset 3D view", exact: true }).click();
  await frames();
  assert.equal(await hash(), reset);
  await viewer.mouse.move(point.x, point.y);
  await viewer.mouse.wheel(0, 160);
  await viewer.mouse.move(0, 0);
  await frames();
  assert.notEqual(await hash(), reset, "Wheel zoom remains available");
  await controls.getByRole("button", { name: "Reset 3D view", exact: true }).click();
  await frames();
  assert.equal(await hash(), reset, "Reset restores camera distance and orientation without resetting model time");
  const unnamed = await controls.getByLabel("3D part").locator("option").evaluateAll(options => options.find(option => option.textContent.startsWith("Unnamed part")).value);
  await controls.getByLabel("3D part").selectOption(unnamed);
  await expect(details).toContainText("No explanation supplied for this part.");
  await expect(details).not.toContainText("A supplied explanation");
  await viewer.screenshot({ path: path.join(output, "three-unnamed-part.png") });
  await controls.getByLabel("3D part").press("Escape");
  await expect(details).toHaveCount(0);
  await scene.focus();
  await frames();
  const keyboardReset = await hash();
  await scene.press("ArrowRight");
  await frames();
  assert.notEqual(await hash(), keyboardReset);
  await scene.press("Home");
  await frames();
  assert.equal(await hash(), keyboardReset);
  await controls.getByRole("button", { name: "Resume model animation", exact: true }).click();
  await expect.poll(hash).not.toBe(reset);
  await controls.getByRole("button", { name: "Pause model animation", exact: true }).click();
  for (const width of [768, 390]) {
    await viewer.setViewportSize({ width, height: 900 });
    await expect(scene).toBeVisible();
    await frames();
    const image = await scene.screenshot();
    const stats = await sharp(image).stats();
    assert.ok(stats.channels.some(channel => channel.stdev > 10), "Mobile scene is nonblank");
    const dimensions = await sharp(image).metadata();
    for (const left of [0, dimensions.width - 4]) {
      const { data: pixels, info } = await sharp(image).extract({ left, top: 0, width: 4, height: dimensions.height }).removeAlpha().raw().toBuffer({ resolveWithObject: true });
      let geometryPixels = 0;
      for (let offset = 0; offset < pixels.length; offset += info.channels) if (pixels[offset + 2] > pixels[offset] + 30 && pixels[offset + 1] > pixels[offset] + 30) geometryPixels++;
      assert.equal(geometryPixels, 0, "Geometry stays inside the mobile frame");
    }
    await controls.getByLabel("3D part").selectOption({ label: "Core block" });
    await expect(details).toBeVisible();
    for (const element of [controls, details]) {
      const bounds = await element.boundingBox();
      assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width + 1 && bounds.y + bounds.height <= 900);
      assert.equal(await element.evaluate(element => element.scrollWidth <= element.clientWidth), true);
    }
    await viewer.screenshot({ path: path.join(output, `three-inspection-${width}.png`) });
    await details.getByRole("button", { name: "Close 3D part details", exact: true }).click();
  }
  await viewer.getByRole("tab", { name: "Document", exact: true }).click();
  await viewer.getByRole("tab", { name: "Study", exact: true }).click();
  await expect(scene).toBeVisible();
  await viewer.getByRole("combobox", { name: "Saved visualization version", exact: true }).selectOption("static");
  await expect(controls.getByRole("button", { name: "Pause model animation", exact: true })).toBeDisabled();
  await expect(controls.getByRole("button", { name: "Pause rotation", exact: true })).toBeEnabled();
  await expect(details).toHaveCount(0);
  await viewer.evaluate(() => document.documentElement.classList.add("dark"));
  await controls.getByRole("button", { name: "Pause rotation", exact: true }).click();
  await controls.getByRole("button", { name: "Reset 3D view", exact: true }).click();
  await controls.getByLabel("3D part").selectOption({ label: "Core block" });
  await expect(details).toBeVisible();
  await viewer.screenshot({ path: path.join(output, "three-inspection-dark.png") });
  await viewer.evaluate(() => document.documentElement.classList.remove("dark"));
  await viewer.reload();
  await expect(scene).toBeVisible();
  await expect(controls.getByRole("button", { name: "Pause model animation", exact: true })).toBeDisabled();
  assert.equal(await scene.count(), 1, "Reload/version switching does not leave duplicate canvases");
  const touchContext = await context.browser().newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, deviceScaleFactor: 2 });
  try {
    const touchViewer = await touchContext.newPage();
    await touchViewer.goto(`${origin}/viewer/${docId}`);
    const touchScene = touchViewer.getByRole("img", { name: "3D visualization", exact: true });
    await expect(touchScene).toBeVisible();
    await touchViewer.getByRole("button", { name: "Pause rotation", exact: true }).tap();
    await touchViewer.getByRole("button", { name: "Reset 3D view", exact: true }).tap();
    const bounds = await touchScene.boundingBox();
    await touchViewer.touchscreen.tap(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
    await expect(touchViewer.getByRole("dialog", { name: "3D part details", exact: true })).toContainText("Core block");
    await touchViewer.screenshot({ path: path.join(output, "three-inspection-touch.png") });
  } finally { await touchContext.close(); }
  assert.equal(getModelCalls(), calls, "Inspection, camera controls and animation playback never call the model");
  await viewer.close();
  console.log("3D inspection: raycast hover/tap, named and unnamed parts, selection outlines, independent pause controls, reset, drag/zoom/keyboard, mobile pixel framing and version cleanup passed.");
}