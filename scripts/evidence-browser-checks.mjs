import assert from "node:assert/strict";
import { expect } from "playwright/test";

export async function checkEvidence({ context, origin, docId, output, getModelCalls }) {
  const viewer = await context.newPage();
  await viewer.setViewportSize({ width: 1440, height: 1000 });
  await viewer.goto(`${origin}/viewer/${docId}`);
  const revision = viewer.getByRole("region", { name: "Visualization revision" });
  await expect(revision).toBeVisible();
  await revision.getByLabel("Visualization format").selectOption("formula");
  await revision.getByRole("button", { name: "Generate", exact: true }).click();
  const main = viewer.getByRole("button", { name: "Evidence for main_latex", exact: true });
  await expect(main).toBeVisible({ timeout: 120000 });
  await expect(revision.getByRole("button", { name: "Generate", exact: true })).toBeEnabled();
  for (const width of [1440, 768, 390]) {
    await viewer.setViewportSize({ width, height: 1000 });
    const formula = viewer.getByTestId("formula-view");
    await expect(formula).toBeVisible();
    const equations = formula.getByRole("region", { name: /equation/ });
    await expect(equations).toHaveCount(3);
    await expect.poll(() => formula.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
    for (const equation of await equations.all()) {
      const state = await equation.evaluate(element => {
        const bounds = element.getBoundingClientRect();
        const parent = element.parentElement.getBoundingClientRect();
        return { contained: bounds.left >= parent.left && bounds.right <= parent.right + 1, fontSize: parseFloat(getComputedStyle(element.firstElementChild).fontSize), overflowX: getComputedStyle(element).overflowX };
      });
      assert.equal(state.contained, true);
      assert.ok(state.fontSize >= 12 && state.fontSize <= 20);
      assert.equal(state.overflowX, "auto");
    }
    const longEquation = formula.getByRole("region", { name: "Derivation equation 2", exact: true });
    await longEquation.scrollIntoViewIfNeeded();
    assert.equal(await longEquation.evaluate(element => { element.scrollLeft = element.scrollWidth; return element.scrollLeft > 0; }), true, "Very long equations remain accessible through a local scrollbar");
    await formula.getByRole("region", { name: "Headline equation", exact: true }).scrollIntoViewIfNeeded();
    await viewer.screenshot({ path: `${output}/long-formula-${width}.png` });
    assert.equal(await viewer.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  }
  await viewer.setViewportSize({ width: 1440, height: 1000 });
  const calls = getModelCalls();
  await main.click();
  const evidence = viewer.getByRole("region", { name: "Claim evidence", exact: true });
  await expect(evidence).toContainText("Excerpt matched in PDF text");
  await evidence.getByRole("button", { name: "Show passage - page 1", exact: true }).click();
  const highlight = viewer.locator("[data-evidence-rect]").first();
  await expect(highlight).toBeVisible();
  const page = viewer.locator('[data-page="0"]');
  const box = await highlight.boundingBox();
  const pageBox = await page.boundingBox();
  assert.ok(box.x >= pageBox.x && box.x + box.width <= pageBox.x + pageBox.width + 1);
  assert.ok(box.y >= pageBox.y && box.y + box.height <= pageBox.y + pageBox.height + 1);
  await viewer.screenshot({ path: `${output}/evidence-formula-desktop.png` });
  await evidence.getByLabel("Evidence claim").selectOption("unmatched");
  await expect(evidence).toContainText("Unsupported / not checked");
  await expect(evidence.getByRole("button", { name: /Show passage/ })).toHaveCount(0);
  await expect(viewer.locator("[data-evidence-rect]")).toHaveCount(0);
  await viewer.getByRole("button", { name: "Evidence for step:1", exact: true }).click();
  await expect(evidence).toContainText("Illustrative assumption");
  await evidence.getByLabel("Evidence claim").selectOption("result");
  await expect(evidence).toContainText("Derivation and calculations have not been independently checked");
  await evidence.getByRole("button", { name: "Momentum equals mass multiplied by velocity.", exact: true }).click();
  await expect(evidence).toContainText("Stated in the paper");
  assert.equal(getModelCalls(), calls, "Inspecting evidence never makes an AI call");
  const versionPicker = revision.getByLabel("Saved visualization version");
  const formulaVersion = await versionPicker.inputValue();
  await evidence.getByRole("button", { name: "Close evidence" }).click();
  await revision.getByLabel("Visualization format").selectOption("2d-text");
  await revision.getByRole("button", { name: "Generate", exact: true }).click();
  await expect(viewer.getByRole("button", { name: "Evidence for paragraph:1", exact: true })).toBeVisible({ timeout: 120000 });
  await expect(viewer.getByRole("status", { name: "PDF evidence highlight" })).toHaveCount(0);
  await expect(revision.getByRole("button", { name: "Generate", exact: true })).toBeEnabled();
  const sourceVersion = await versionPicker.inputValue();
  await viewer.reload();
  await viewer.getByRole("button", { name: "Evidence for paragraph:1", exact: true }).click();
  await expect(evidence).toContainText("Excerpt matched in PDF text");
  await evidence.getByRole("button", { name: "Close evidence" }).click();
  const beforeRestore = getModelCalls();
  await versionPicker.selectOption(formulaVersion);
  await main.click();
  await expect(evidence).toContainText("Excerpt matched in PDF text");
  assert.equal(getModelCalls(), beforeRestore);
  await viewer.setViewportSize({ width: 390, height: 844 });
  await evidence.getByRole("button", { name: "Show passage - page 1", exact: true }).click();
  await expect(viewer.getByRole("tab", { name: "Document", exact: true })).toHaveAttribute("aria-selected", "true");
  await expect(highlight).toBeVisible();
  const beforeZoom = await highlight.boundingBox();
  await viewer.getByRole("button", { name: "Zoom in", exact: true }).click();
  await expect.poll(async () => (await highlight.boundingBox()).width).toBeGreaterThan(beforeZoom.width);
  await viewer.screenshot({ path: `${output}/evidence-pdf-mobile.png` });
  await viewer.getByRole("button", { name: "Back to visualization", exact: true }).click();
  await expect(evidence).toBeVisible();
  const evidenceBox = await evidence.boundingBox();
  assert.ok(evidenceBox.x >= 0 && evidenceBox.x + evidenceBox.width <= 390 && evidenceBox.y + evidenceBox.height <= 844);
  await viewer.screenshot({ path: `${output}/evidence-panel-mobile.png` });
  await evidence.getByRole("button", { name: "Close evidence" }).click();
  await versionPicker.selectOption(sourceVersion);
  await expect(viewer.getByRole("status", { name: "PDF evidence highlight" })).toHaveCount(0);
  await revision.getByLabel("Visualization format").selectOption("interactive");
  await revision.getByRole("button", { name: "Generate", exact: true }).click();
  await viewer.getByRole("button", { name: "Evidence for code:1", exact: true }).click({ timeout: 120000 });
  await expect(viewer.getByRole("status", { name: "Evidence warnings", exact: true })).toContainText("2 evidence claim(s) omitted");
  await expect(viewer.getByTestId("interactive-lesson")).toBeVisible();
  await expect(revision.getByRole("alert")).toHaveCount(0);
  await expect(evidence).toContainText("Excerpt matched in PDF text");
  assert.equal(await viewer.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await viewer.route(`**/api/doc/${docId}`, async route => {
    const response = await route.fetch();
    const document = await response.json();
    document.pages = document.pages.map(page => ({ ...page, text: page.text + " Changed source." }));
    await route.fulfill({ json: document });
  });
  await viewer.reload();
  await viewer.getByRole("button", { name: "Evidence for code:1", exact: true }).click();
  await evidence.getByRole("button", { name: "Show passage - page 1", exact: true }).click();
  await expect(evidence.getByRole("alert")).toContainText("source page has changed");
  await expect(viewer.locator("[data-evidence-rect]")).toHaveCount(0);
  await viewer.close();
  console.log("Evidence: matched/unmatched excerpts, derivations, assumptions, dependencies, source highlights, version persistence, simulator code, and mobile return flow passed.");
}