import assert from "node:assert/strict";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { PDFDocument, StandardFonts } from "pdf-lib";
import { expect } from "playwright/test";

export async function checkSourceRetrieval({ context, origin, docId, dataDirectory, output, getModelCalls }) {
  const pdf = await PDFDocument.create();
  const page = pdf.addPage([595, 842]);
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  page.drawText("References", { x: 40, y: 790, size: 20, font });
  page.drawText(Array.from({ length: 16 }, (_, index) => `[${index + 1}] Example. 2017. Mechanics Study Guide. Bibliographic entry.`).join("\n"), { x: 40, y: 745, size: 11, font, lineHeight: 25 });
  const form = new FormData();
  form.set("file", new Blob([await pdf.save()], { type: "application/pdf" }), "references.pdf");
  const response = await fetch(`${origin}/api/upload`, { method: "POST", body: form });
  assert.equal(response.status, 200);
  const bibliography = await response.json();
  const tag = { id: "reference-test", page: 0, endX: 200, endY: 200, fontHeight: 12, type: "2d-text", label: "Mechanics Study Guide", ready: true, generating: false, revision: 0, spec: { type: "2d-text", title: "Bibliography only", caption: "Citation only.", body_markdown: "The bibliography does not supply the paper contents.", citations: [] }, concept: { type: "2d-text", label: "Mechanics Study Guide", context: 'Summarize the paper "Mechanics Study Guide".', anchor: "Mechanics Study Guide" } };
  await writeFile(path.join(dataDirectory, "docs", bibliography.docId, "tags.json"), JSON.stringify({ v: 1, docId: bibliography.docId, savedAt: Date.now(), activeTagId: tag.id, pagesAnalyzed: [0], tags: [tag] }));
  const viewer = await context.newPage();
  await viewer.setViewportSize({ width: 1440, height: 1000 });
  await viewer.goto(`${origin}/viewer/${bibliography.docId}`);
  const revision = viewer.getByRole("region", { name: "Visualization revision", exact: true });
  await expect(revision).toBeVisible();
  await expect(revision.getByLabel("Public paper URL")).toBeVisible();
  await expect(revision.getByRole("link", { name: "Import a reference PDF" })).toHaveAttribute("href", "/");
  await revision.getByRole("button", { name: "Generate", exact: true }).click();
  const marker = viewer.getByRole("button", { name: "Evidence for paragraph:1", exact: true });
  await expect(marker).toBeVisible({ timeout: 120000 });
  await expect(revision.getByRole("button", { name: "Generate", exact: true })).toBeEnabled();
  const state = await (await fetch(`${origin}/api/tags/${bibliography.docId}`)).json();
  const saved = state.file.tags.find(item => item.id === tag.id);
  assert.equal(saved.spec.evidence.docId, docId);
  assert.equal(saved.spec.evidence.source.differentDocument, true);
  assert.equal(saved.spec.evidence.claims.find(claim => claim.id === "definition").verification, "excerpt_matched");
  assert.equal(saved.spec.evidence.warnings, undefined);
  assert.ok(saved.versions.some(version => version.spec.title === "Bibliography only"));
  const generatedVersion = saved.versionId;
  await marker.click();
  const evidence = viewer.getByRole("region", { name: "Claim evidence", exact: true });
  await expect(evidence).toContainText("Excerpt matched in PDF text");
  const sourceLink = evidence.getByRole("link", { name: "Open source PDF - page 1", exact: true });
  await expect(sourceLink).toHaveAttribute("href", `/api/pdf/${docId}#page=1`);
  await expect(evidence.getByRole("button", { name: /Show passage/ })).toHaveCount(0);
  const opening = viewer.waitForEvent("popup");
  await sourceLink.click();
  const sourcePage = await opening;
  await sourcePage.waitForURL(`${origin}/api/pdf/${docId}#page=1`);
  await sourcePage.close();
  await viewer.screenshot({ path: path.join(output, "source-retrieval-desktop.png") });
  await viewer.setViewportSize({ width: 390, height: 844 });
  await viewer.getByRole("tab", { name: "Study", exact: true }).click();
  await expect(evidence).toBeVisible();
  assert.equal(await viewer.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const bounds = await evidence.boundingBox();
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390 && bounds.y + bounds.height <= 844);
  await viewer.screenshot({ path: path.join(output, "source-retrieval-mobile.png") });
  await viewer.reload();
  await marker.click();
  await expect(sourceLink).toHaveAttribute("href", `/api/pdf/${docId}#page=1`);
  await evidence.getByRole("button", { name: "Close evidence" }).click();
  const calls = getModelCalls();
  const picker = revision.getByLabel("Saved visualization version");
  const oldVersion = saved.versions.find(version => version.spec.title === "Bibliography only").id;
  await picker.selectOption(oldVersion);
  await expect(viewer.locator('[aria-label="Evidence source document"]')).toHaveCount(0);
  await picker.selectOption(generatedVersion);
  await expect(viewer.locator('[aria-label="Evidence source document"]')).toContainText("lecture");
  assert.equal(getModelCalls(), calls);
  const invalid = await fetch(`${origin}/api/settings`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ publicSourceRetrieval: "true" }) });
  assert.equal(invalid.status, 400);
  await viewer.getByRole("button", { name: "Settings", exact: true }).click();
  const toggle = viewer.getByRole("switch", { name: "Public paper retrieval", exact: true });
  await expect(toggle).toBeEnabled();
  await expect(toggle).not.toBeChecked();
  await toggle.click();
  await expect.poll(async () => (await (await fetch(`${origin}/api/settings`)).json()).publicSourceRetrieval).toBe(true);
  await expect(toggle).toBeChecked();
  await viewer.reload();
  await viewer.getByRole("button", { name: "Settings", exact: true }).click();
  await expect(toggle).toBeChecked();
  await toggle.click();
  await expect.poll(async () => (await (await fetch(`${origin}/api/settings`)).json()).publicSourceRetrieval).toBe(false);
  await expect(toggle).not.toBeChecked();
  await viewer.route("**/api/settings", route => route.request().method() === "POST" ? route.fulfill({ status: 500, json: { error: "Synthetic save failure" } }) : route.continue());
  await expect(toggle).toBeEnabled();
  await toggle.click();
  await expect(viewer.getByRole("region", { name: "Source retrieval", exact: true }).getByRole("alert")).toContainText("Could not save");
  await expect(toggle).not.toBeChecked();
  await viewer.unroute("**/api/settings");
  await viewer.screenshot({ path: path.join(output, "source-retrieval-settings.png") });
  await viewer.close();
  console.log("Source retrieval: bibliography-to-library lookup, correct PDF links, saved evidence versions, responsive UI, and opt-in persistence/failure checks passed.");
}